/*==============================================================================
  011 - Triggers  (PostgreSQL)

  Port of db/sqlserver/011_triggers.sql.

  SQL Server allows one trigger to cover INSERT, UPDATE and DELETE; PostgreSQL
  needs a separate trigger per operation when transition tables are involved,
  because OLD TABLE only exists for UPDATE/DELETE and NEW TABLE only for
  INSERT/UPDATE. So four source triggers become seven here, plus one that has
  no SQL Server counterpart (see ROWVERSION below).

  Three changes from what AWS SCT generated:

    * SCT worked around the missing transition table by having the function
      CREATE TEMPORARY TABLE ... WITH NO DATA on every fire. The functions here
      branch on TG_OP and read only the transition table that exists, which is
      both cheaper and clearer.

    * SCT serialized the audit row images with json_agg(), which produces a
      JSON *array*. SQL Server's FOR JSON PATH, WITHOUT_ARRAY_WRAPPER produces
      an *object*, and audit.vw_RecentChanges depends on that: jsonb_each_text
      needs an object to expand into key/value pairs. jsonb_build_object is
      used instead.

    * client.tr_ClientDirectory_Insert - the INSTEAD OF INSERT trigger on
      client.vw_ClientDirectory - is missing from SCT's output entirely. There
      is no trigger on that view anywhere in the generated file. It is written
      out again below.

  Statement-level triggers with transition tables are kept (rather than
  simplified to FOR EACH ROW) because they match SQL Server's set-based trigger
  semantics: one fire per statement, seeing all affected rows at once.

  Error numbers travel as SQLSTATE, so a harness asserts on the same value
  against both engines: THROW 50007 -> ERRCODE '50007'.
==============================================================================*/

SET client_min_messages = warning;


/*------------------------------------------------------------------------------
  Serializes one client row to a JSON object, matching the column list the
  SQL Server trigger passes to FOR JSON PATH.

  jsonb_build_object rather than to_jsonb(row): to_jsonb would include every
  column, including the rowversion bytes and the audit timestamps, which the
  SQL Server version deliberately leaves out.
------------------------------------------------------------------------------*/
CREATE OR REPLACE FUNCTION client.fn_client_rowimage(rec client.client)
RETURNS JSONB
AS
$BODY$
    SELECT jsonb_build_object(
        'clientid',       rec.clientid,
        'clientcode',     rec.clientcode,
        'clienttype',     rec.clienttype,
        'displayname',    rec.displayname,
        'firstname',      rec.firstname,
        'lastname',       rec.lastname,
        'legalname',      rec.legalname,
        'sin',            rec.sin,
        'businessnumber', rec.businessnumber,
        'provincecode',   rec.provincecode,
        'maritalstatus',  rec.maritalstatus,
        'isactive',       rec.isactive,
        'onboardeddate',  rec.onboardeddate);
$BODY$
LANGUAGE sql IMMUTABLE;

DROP TRIGGER IF EXISTS tr_journalline_nopostededits_after_update ON acct.journalline;
DROP TRIGGER IF EXISTS tr_journalline_nopostededits_after_delete ON acct.journalline;
DROP TRIGGER IF EXISTS tr_client_audit_after_insert ON client.client;
DROP TRIGGER IF EXISTS tr_client_audit_after_update ON client.client;
DROP TRIGGER IF EXISTS tr_client_audit_after_delete ON client.client;
DROP TRIGGER IF EXISTS tr_client_biu ON client.client;
DROP TRIGGER IF EXISTS tr_t1return_statushistory ON tax.t1return;
